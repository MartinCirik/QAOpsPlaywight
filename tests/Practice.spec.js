import { test, expect } from '@playwright/test';

test('Practise', async ({ page }) => {
  await page.goto('https://eventhub.rahulshettyacademy.com/login');
  await page.getByPlaceholder("you@email.com").fill("mcirik19@gmail.com");
  await page.getByPlaceholder("••••••").fill("Karol050290*");
  await page.getByRole('button', { name: 'Sign In' }).click();
  await expect(page.getByRole('main')).toContainText('Browse Events →');
  await page.getByRole('button', { name: 'Admin' }).click();
  await page.getByRole('navigation').getByRole('link', { name: 'Manage Events' }).click();
  const uniqueEventTitle = `QA World Manifest ${Date.now()}`;
  console.log('Created unique name of event: ' + uniqueEventTitle);
  await page.locator('#event-title-input').fill(uniqueEventTitle);
  await page.locator('#admin-event-form textarea').fill('Toto je ukážkový popis pre novú udalosť.');
  await page.getByLabel('City').fill('Bratislava');
  await page.getByLabel('Venue').fill('Incheba Expo');
  await page.getByLabel('Event Date & Time').click();
  await page.getByLabel('Event Date & Time').fill('2026-12-12T15:30');
  await page.locator("input[placeholder='0.00']").fill('100');
  await page.getByLabel('Total Seats').fill('50');
  await page.locator('#add-event-btn').click();
  const toastMessage = page.locator('text=Event created!');
  await expect(toastMessage).toBeVisible();
  await page.getByTestId('nav-events').click();
  const cards = page.locator('[data-testid="event-card"]');
  await expect(cards.first()).toBeVisible();
  const matchedCard = cards.filter({ hasText: uniqueEventTitle });
  await expect(matchedCard).toBeVisible({ timeout: 5000 });
  const seatTextElement = matchedCard.locator('text=seat');
  const fullSeatText = await seatTextElement.textContent();
  const seatsBeforeBooking = parseInt(fullSeatText.match(/\d+/)[0], 10);
  console.log(`Počet miest pred rezerváciou: ${seatsBeforeBooking}`);
  await matchedCard.getByTestId('book-now-btn').click();
  await expect(page.locator('#ticket-count')).toHaveText('1');
  await page.getByLabel('Full Name').fill('Martin Čirik');
  await page.locator('#customer-email').fill('mcirik19@gmail.com');
  await page.getByPlaceholder('+91 98765 43210').fill('+421910982039');
  await page.locator('.confirm-booking-btn').click();
  const bookingRefElement = page.locator('.booking-ref').first();
  await expect(bookingRefElement).toBeVisible();
  const rawText = await bookingRefElement.innerText();
  const bookingRef = rawText.trim();
  console.log(`Získaný kód rezervácie: ${bookingRef}`);
  await page.getByRole('link', { name: 'View My Bookings' }).click();
  await expect(page).toHaveURL(/\/bookings$/);
  const bookingCards = page.locator('#booking-card');
  await expect(bookingCards.first()).toBeVisible();
  const matchedBookingCard = bookingCards.filter({has: page.locator('.booking-ref'), hasText: bookingRef});
  await expect(matchedBookingCard).toBeVisible();
  await expect(matchedBookingCard).toContainText(uniqueEventTitle);
  await page.getByTestId('nav-events').click();
  const eventCards = page.locator('[data-testid="event-card"]');
  await expect(eventCards.first()).toBeVisible();
  const updatedMatchedCard = eventCards.filter({ hasText: uniqueEventTitle });
  await expect(updatedMatchedCard).toBeVisible();
  const updatedSeatTextElement = updatedMatchedCard.locator('text=seat');
  const updatedFullSeatText = await updatedSeatTextElement.textContent();
  const seatsAfterBooking = parseInt(updatedFullSeatText.match(/\d+/)[0], 10);
  console.log(`Počet miest po rezervácii: ${seatsAfterBooking}`);
  expect(seatsAfterBooking).toBe(seatsBeforeBooking - 1);
  console.log("Matematické overenie úspešné! Počet miest klesol presne o 1.");
})
